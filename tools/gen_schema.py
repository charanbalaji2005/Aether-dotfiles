#!/usr/bin/python3
"""Regenerates lib/aether/_schema_data.py from core/Config.qml.

The shell's Config.qml is the single source of truth for config.json: keys,
types and defaults are declared there (and enum choices in the trailing
comment, written as `"a" | "b" | "c"`). The Python backend validates,
migrates, imports and exports the same file, so it needs the same schema —
this script derives it instead of maintaining a second copy by hand.

    python3 tools/gen_schema.py            rewrite the data module
    python3 tools/gen_schema.py --check    exit 1 if it is out of date (CI)
"""
import json
import os
import pprint
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
QML = os.path.join(REPO, "config", "quickshell", "aether-shell", "core", "Config.qml")
OUT = os.path.join(REPO, "lib", "aether", "_schema_data.py")

SECTION = re.compile(r"property JsonObject (\w+): JsonObject \{(.*?)\n            \}", re.S)
PROP = re.compile(r"^\s*property (bool|int|real|string|var) (\w+): (.*)$")
STRING_LIT = re.compile(r'^"(?:\\.|[^"\\])*"')


def split_value(rest):
    """(value, comment) — a string literal may contain '//' (URLs), so it is
    matched as a whole before looking for a trailing comment."""
    m = STRING_LIT.match(rest)
    if m:
        tail = rest[m.end():]
        c = re.match(r"\s*//\s*(.*)$", tail)
        return m.group(0), (c.group(1) if c else None)
    v = re.match(r"^(.*?)\s*(?://\s*(.*))?$", rest)
    return v.group(1), v.group(2)


def parse(text):
    schema = {}
    for sec in SECTION.finditer(text):
        fields = {}
        for line in sec.group(2).splitlines():
            m = PROP.match(line)
            if not m:
                continue
            qtype, name, rest = m.groups()
            raw, comment = split_value(rest.strip())
            raw = raw.strip()
            if qtype == "var":
                default = json.loads(raw.strip("()").replace("'", '"'))
                kind = "list" if isinstance(default, list) else "map"
            elif qtype == "bool":
                default, kind = raw == "true", "bool"
            elif qtype == "int":
                default, kind = int(raw), "int"
            elif qtype == "real":
                default, kind = float(raw), "real"
            else:
                default, kind = json.loads(raw), "str"
            spec = {"type": kind, "default": default}
            # Enum choices: the comment starts with two or more quoted words
            # separated by '|'. Prose after the list is ignored.
            if kind == "str" and comment:
                head = re.match(r'((?:"[\w-]*"\s*\|\s*)+"[\w-]*")', comment)
                if head:
                    spec["choices"] = re.findall(r'"([\w-]*)"', head.group(1))
            fields[name] = spec
        schema[sec.group(1)] = fields
    return schema


def render(schema):
    return (
        '"""GENERATED by tools/gen_schema.py from core/Config.qml — do not edit.\n\n'
        'Regenerate with: python3 tools/gen_schema.py\n"""\n\n'
        "SCHEMA = " + pprint.pformat(schema, width=110, sort_dicts=False) + "\n"
    )


def main():
    with open(QML, encoding="utf-8") as fh:
        text = render(parse(fh.read()))
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = ""
        if current != text:
            sys.stderr.write("lib/aether/_schema_data.py is out of date: run python3 tools/gen_schema.py\n")
            return 1
        print("schema data is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s (%d sections, %d keys)" % (OUT, len(parse(open(QML, encoding="utf-8").read())),
                                              sum(len(v) for v in parse(open(QML, encoding="utf-8").read()).values())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
