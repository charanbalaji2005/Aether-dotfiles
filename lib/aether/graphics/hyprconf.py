"""Generates the machine-specific Hyprland fragments that hyprland.conf sources:

    ~/.config/aether-shell/hypr/hardware.conf   GPU environment (this module)
    ~/.config/aether-shell/hypr/profile.conf    visual/perf profile (performance.py)

They live outside the repository on purpose: the repo's config/hypr is
symlinked into ~/.config/hypr, so anything generated there would show up as
uncommitted changes and would be wrong on the next machine you clone onto.

Rules for hardware.conf:
  * Only variables that are needed for the detected hardware are written.
  * Obsolete NVIDIA workarounds (WLR_NO_HARDWARE_CURSORS, GBM_BACKEND,
    render:explicit_sync, ...) are never written.
  * On hybrid laptops nothing NVIDIA-specific is set globally — the desktop
    stays on the integrated GPU, and apps opt into the dGPU with
    `aether gpu run`. Changing the compositor's GPU requires --primary.
"""

from __future__ import annotations

import difflib
import os
import re
import shutil
import time
from typing import Dict, List, Optional, Tuple

from ..hw import gpu as gpu_mod
from ..hw import system
from ..util import Context, config_dir, parse_version, version_at_least
from . import nvidia

HEADER_MARK = "# Generated by `aether"


def fragment_dir() -> str:
    return os.path.join(config_dir(), "hypr")


def hardware_conf_path() -> str:
    return os.path.join(fragment_dir(), "hardware.conf")


def profile_conf_path() -> str:
    return os.path.join(fragment_dir(), "profile.conf")


def _slot_tag(slot: str) -> str:
    return re.sub(r"[^0-9A-Za-z]", "-", slot)


def offload_env(gpu: gpu_mod.GPU) -> Dict[str, str]:
    """Environment that makes a program render on ``gpu`` (PRIME offload)."""
    if gpu["vendor"] == "nvidia" and gpu["driver"] == "nvidia":
        return {
            "__NV_PRIME_RENDER_OFFLOAD": "1",
            "__GLX_VENDOR_LIBRARY_NAME": "nvidia",
            "__VK_LAYER_NV_optimus": "NVIDIA_only",
        }
    # Mesa drivers (amdgpu, i915/xe, nouveau): DRI_PRIME selects by PCI tag.
    return {"DRI_PRIME": "pci-" + gpu["slot"].replace(":", "_").replace(".", "_")}


def generate_hardware_conf(
    ctx: Context,
    primary_slot: Optional[str] = None,
    link_dir: Optional[str] = None,
) -> Tuple[str, List[str], List[Tuple[str, str]]]:
    """Return (file text, notes for the user, symlinks to create)."""
    gpus = gpu_mod.detect(ctx)
    topo = gpu_mod.topology(gpus)
    hypr_ver = parse_version(system.hyprland_version(ctx))
    hypr_txt = ".".join(map(str, hypr_ver)) if hypr_ver else "unknown"
    link_dir = link_dir or fragment_dir()
    notes: List[str] = []
    links: List[Tuple[str, str]] = []
    body: List[str] = []

    lines = [
        "%s graphics configure` on %s." % (HEADER_MARK, time.strftime("%Y-%m-%d %H:%M")),
        "# Machine-specific GPU settings. Regenerate after hardware or driver changes;",
        "# hand edits are overwritten (a timestamped backup is kept next to this file).",
        "#",
        "# Detected layout: %s | Hyprland %s" % (topo["layout"], hypr_txt),
    ]
    for g in gpus:
        lines.append("#   %s  %-8s %-10s %s%s" % (g["slot"], g["vendor"], g["driver"] or "no-driver", g["name"], "  (boot)" if g["bootVga"] else ""))
    lines.append("")

    primary = None
    if primary_slot:
        primary = next((g for g in gpus if g["slot"] == primary_slot or g["slot"].endswith(primary_slot)), None)
        if primary is None:
            raise ValueError("No GPU with PCI slot %r. Detected: %s" % (primary_slot, ", ".join(g["slot"] for g in gpus) or "none"))

    # -- explicit compositor GPU selection (opt-in only) -----------------
    if primary is not None and len(gpus) > 1:
        ordered = [primary] + [g for g in gpus if g is not primary and g["vendor"] not in ("virtio", "qxl")]
        paths = []
        for g in ordered:
            link = os.path.join(link_dir, "gpu-" + _slot_tag(g["slot"]))
            links.append((g["byPath"], link))
            paths.append(link)
        var = "AQ_DRM_DEVICES" if (hypr_ver is None or version_at_least(hypr_ver, (0, 42))) else "WLR_DRM_DEVICES"
        body += [
            "# Compositor GPU order chosen explicitly with --primary %s." % primary["slot"],
            "# Paths are symlinks to /dev/dri/by-path because ':' in PCI paths would",
            "# break the colon-separated list. Remove this line to restore the default.",
            "env = %s,%s" % (var, ":".join(paths)),
            "",
        ]
        notes.append("Hyprland will render on %s (%s) after you log out and back in." % (primary["name"], primary["slot"]))
        if topo["hybrid"] and primary["kind"] == "discrete":
            notes.append("Rendering the desktop on the discrete GPU keeps it awake permanently and costs battery life.")

    nvidia_drives_desktop = (
        (primary is not None and primary["vendor"] == "nvidia")
        or (primary is None and topo["nvidiaIsPrimary"] and not topo["hybrid"])
    )
    nv_primary = primary if (primary is not None and primary["vendor"] == "nvidia") else next(
        (g for g in gpus if g["vendor"] == "nvidia" and g["bootVga"]), None
    )

    if nvidia_drives_desktop and nv_primary is not None:
        if nv_primary["driver"] == "nvidia":
            st = nvidia.state(ctx, gpus)
            body += [
                "# NVIDIA proprietary driver drives the desktop.",
                "env = __GLX_VENDOR_LIBRARY_NAME,nvidia",
            ]
            vaapi_lib = any(ctx.exists(d + "/dri/nvidia_drv_video.so") for d in ("/usr/lib64", "/usr/lib"))
            if vaapi_lib:
                body += ["env = LIBVA_DRIVER_NAME,nvidia", "env = NVD_BACKEND,direct"]
            else:
                body.append("# VA-API through NVDEC not set up: libva-nvidia-driver is not installed.")
            drv = parse_version(st.get("driverVersion") or st.get("moduleBuiltForRunningKernel"))  # type: ignore[arg-type]
            if drv is not None and drv[0] < 555:
                if hypr_ver is not None and version_at_least(hypr_ver, (0, 41)):
                    body += [
                        "# Driver %s predates explicit sync (555); hardware cursors can glitch." % ".".join(map(str, drv)),
                        "cursor {",
                        "    no_hardware_cursors = true",
                        "}",
                    ]
                notes.append("NVIDIA driver %s is older than 555 — update it for explicit sync support." % ".".join(map(str, drv)))
            body += [
                "# Deliberately NOT set: GBM_BACKEND (breaks some apps, unneeded on modern",
                "# drivers), WLR_NO_HARDWARE_CURSORS (obsolete), render:explicit_sync (removed",
                "# from Hyprland; explicit sync is automatic with driver 555+).",
                "",
            ]
            if st.get("drmModeset") == "N":
                notes.append("nvidia_drm modeset is OFF — Hyprland will not start on this GPU until it is enabled. See `aether graphics verify`.")
        elif nv_primary["driver"] == "nouveau":
            body += ["# NVIDIA GPU runs on nouveau: no special environment needed.", ""]
            notes.append("The NVIDIA GPU uses nouveau; performance is limited. See `aether graphics drivers`.")
        else:
            body += ["# NVIDIA GPU has no usable kernel driver bound; no settings written.", ""]
            notes.append("The NVIDIA GPU has no driver bound — run `aether graphics drivers`.")
    elif topo["hybrid"]:
        dgpus = [g for g in gpus if g["kind"] == "discrete"]
        body += [
            "# Hybrid graphics: the desktop stays on the integrated GPU (default).",
            "# Nothing vendor-specific is forced globally. Run a program on the",
            "# discrete GPU with:   aether gpu run <command>",
        ]
        for g in dgpus:
            env = " ".join("%s=%s" % kv for kv in offload_env(g).items())
            body.append("#   %s -> %s" % (g["slot"], env))
        body.append("")
        notes.append("Hybrid graphics detected: desktop stays on the integrated GPU; use `aether gpu run <cmd>` for the discrete GPU.")
        boot_nv = next((g for g in dgpus if g["vendor"] == "nvidia" and g["bootVga"]), None)
        if boot_nv is not None:
            notes.append(
                "The NVIDIA GPU (%s) is the firmware boot display. On a desktop with monitors plugged into it, "
                "run `aether graphics configure --primary %s` so Hyprland renders there." % (boot_nv["slot"], boot_nv["slot"])
            )
    elif not gpus:
        body += ["# No GPU detected; nothing to configure.", ""]
    else:
        body += ["# %s graphics on the in-kernel Mesa drivers need no extra environment." % ", ".join(sorted({g["vendorLabel"] for g in gpus})), ""]

    if any(g["kind"] == "virtual" for g in gpus) and not any(g["kind"] in ("integrated", "discrete") for g in gpus):
        body += [
            "# Virtual machine GPU. If Hyprland renders incorrectly, enable 3D",
            "# acceleration (virtio-gpu with virgl) in the hypervisor.",
            "",
        ]

    return "\n".join(lines + body).rstrip() + "\n", notes, links


def diff(old: str, new: str, path: str) -> str:
    return "".join(
        difflib.unified_diff(old.splitlines(True), new.splitlines(True), fromfile=path + " (current)", tofile=path + " (new)")
    )


def write_fragment(path: str, text: str, links: Optional[List[Tuple[str, str]]] = None) -> Optional[str]:
    """Write ``text`` to ``path`` atomically, backing up the previous file.

    Returns the backup path (None if there was nothing to back up).
    """
    os.makedirs(os.path.dirname(path), exist_ok=True)
    backup = None
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            if fh.read() == text:
                return None
        backup = "%s.bak-%s" % (path, time.strftime("%Y%m%d-%H%M%S"))
        shutil.copy2(path, backup)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, path)
    for target, link in links or []:
        try:
            if os.path.islink(link) or os.path.exists(link):
                os.remove(link)
            os.symlink(target, link)
        except OSError:
            pass
    _prune_backups(path, keep=5)
    return backup


def _prune_backups(path: str, keep: int) -> None:
    d, base = os.path.split(path)
    try:
        backups = sorted(f for f in os.listdir(d) if f.startswith(base + ".bak-"))
    except OSError:
        return
    for old in backups[:-keep]:
        try:
            os.remove(os.path.join(d, old))
        except OSError:
            pass


def compat_conf_path() -> str:
    return os.path.join(fragment_dir(), "compat.conf")


def generate_compat_conf(ctx: Context) -> str:
    """Settings whose syntax depends on the installed Hyprland version.

    Hyprland 0.51 replaced the `gestures { workspace_swipe = ... }` options
    with the `gesture =` keyword; writing the wrong one is a config error.
    """
    ver = parse_version(system.hyprland_version(ctx))
    vtxt = ".".join(map(str, ver)) if ver else "unknown"
    head = (
        "%s hyprland compat` on %s for Hyprland %s.\n"
        "# Version-dependent syntax only. Regenerate after upgrading Hyprland:\n"
        "#   aether hyprland compat\n\n"
    ) % (HEADER_MARK, time.strftime("%Y-%m-%d %H:%M"), vtxt)
    if ver is None:
        return head + "# Hyprland version unknown: touchpad workspace gestures left unset.\n"
    if version_at_least(ver, (0, 51)):
        return head + "# Three-finger horizontal swipe switches workspaces.\ngesture = 3, horizontal, workspace\n"
    return head + "gestures {\n    workspace_swipe = true\n    workspace_swipe_fingers = 3\n}\n"


def ensure_defaults() -> List[str]:
    """Create empty-but-valid fragments if missing so `source =` never fails."""
    created = []
    for path, what in ((hardware_conf_path(), "graphics configure"), (profile_conf_path(), "performance hyprland <profile>"),
                       (compat_conf_path(), "hyprland compat")):
        if not os.path.exists(path):
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write("# Placeholder created by AetherOS. Generate real settings with: aether %s\n" % what)
            created.append(path)
    return created
