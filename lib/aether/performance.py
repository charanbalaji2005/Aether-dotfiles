# -- power profiles ----------------------------------------------------------

def power_profile_state(ctx: Context) -> Dict[str, object]:
    if not ctx.which("powerprofilesctl"):
        return {
            "available": False,
            "reason": "powerprofilesctl not found — install power-profiles-daemon (or tuned-ppd on Fedora 41+)",
        }
    cur = ctx.run(["powerprofilesctl", "get"], timeout=5)
    if not cur.ok:
        return {"available": False, "reason": (cur.err or "powerprofilesctl get failed").strip()}
    lst = ctx.run(["powerprofilesctl", "list"], timeout=5)
    profiles: List[str] = []
    for line in lst.out.splitlines():
        s = line.strip().lstrip("*").strip()
        if s.endswith(":") and s[:-1] in POWER_PROFILES:
            profiles.append(s[:-1])
    return {"available": True, "active": cur.out.strip(), "profiles": profiles or list(POWER_PROFILES)}


def set_power_profile(ctx: Context, profile: str) -> Dict[str, object]:
    if profile not in POWER_PROFILES:
        return {"ok": False, "error": "unknown profile %r (choose: %s)" % (profile, ", ".join(POWER_PROFILES))}
    st = power_profile_state(ctx)
    if not st.get("available"):
        return {"ok": False, "error": st.get("reason")}
    if profile not in st.get("profiles", []):  # type: ignore[operator]
        return {"ok": False, "error": "this machine does not offer the %r profile (available: %s)" % (profile, ", ".join(st["profiles"]))}  # type: ignore[arg-type]
    res = ctx.run(["powerprofilesctl", "set", profile], timeout=10)
    if not res.ok:
        return {"ok": False, "error": (res.err or res.out).strip() or "powerprofilesctl set failed"}
    return {"ok": True, "active": profile}


# -- Hyprland profiles -------------------------------------------------------

def render_hypr_profile(name: str) -> str:
    prof = HYPR_PROFILES[name]
    return (
        "# Generated by `aether performance hyprland %s` on %s.\n"
        "# %s\n"
        "# Sourced last by hyprland.conf, so these values override the defaults.\n"
        "# AETHER_PROFILE=%s\n\n%s"
    ) % (name, time.strftime("%Y-%m-%d %H:%M"), prof["summary"], name, prof["body"])


def current_hypr_profile(path: str) -> Optional[str]:
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if line.startswith("# AETHER_PROFILE="):
                    return line.split("=", 1)[1].strip()
    except OSError:
        return None
    return None


def hypr_profile_exists(path: str) -> bool:
    return os.path.isfile(path)
