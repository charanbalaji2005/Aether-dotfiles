"""Performance profiles.

Two independent knobs:

1. System power profile (balanced / performance / power-saver) through
   ``powerprofilesctl`` — the D-Bus API shared by power-profiles-daemon and
   tuned-ppd (Fedora 41+). This is the kernel/firmware-sanctioned way to
   trade power for speed: AetherOS never writes governors, undervolts,
   overclocks or changes power limits itself.

2. Hyprland visual profile (quality / balanced / low-latency / battery),
   written to ~/.config/aether-shell/hypr/profile.conf, which hyprland.conf
   sources last so it overrides the defaults. Hyprland reloads its config
   automatically when a sourced file changes — no compositor restart.
"""

