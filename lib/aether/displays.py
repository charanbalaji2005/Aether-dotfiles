"""Displays: list, apply with automatic revert, profiles per monitor set.

Safety model (a wrong mode can leave you with a black screen):
  1. The current per-machine display fragment is saved as displays.conf.prev
     and the live monitor lines are recorded.
  2. The change is applied live (`hyprctl keyword monitor …`) and persisted.
  3. A detached watchdog process starts. Unless `aether display confirm` runs
     within the timeout (the Settings dialog does this when you click Keep),
     it restores the previous fragment and live configuration by itself —
     even if the shell has crashed or the screen shows nothing.

Monitors are addressed as `desc:<description>` in the fragment, so a display
keeps its settings whichever port it is plugged into. Only modes Hyprland
reports in `availableModes` are accepted.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import time
from typing import Any, Dict, List, Optional

from .util import Context, config_dir, state_dir

SCALES = (1.0, 1.25, 1.333333, 1.5, 1.6, 1.666667, 1.75, 2.0, 2.4, 2.5, 3.0)
MODE_RE = re.compile(r"^(\d{3,5})x(\d{3,5})@(\d{2,3}(?:\.\d+)?)Hz$")
POS_RE = re.compile(r"^(auto|-?\d{1,5}x-?\d{1,5})$")
DESC_RE = re.compile(r"^[^,#\n\r]{1,200}$")


def fragment_path() -> str:
    return os.path.join(config_dir(), "hypr", "displays.conf")


def profiles_path() -> str:
    return os.path.join(config_dir(), "displays-profiles.json")


def token_path() -> str:
    return os.path.join(state_dir(), "display-pending.json")


def monitors(ctx: Context) -> Optional[List[Dict[str, Any]]]:
    res = ctx.run(["hyprctl", "-j", "monitors", "all"], timeout=5)
    if not res.ok:
        return None
    try:
        data = json.loads(res.out)
    except ValueError:
        return None
    out = []
    for m in data:
        out.append({
            "name": m.get("name"), "description": (m.get("description") or "").strip(),
            "make": m.get("make"), "model": m.get("model"), "serial": m.get("serial"),
            "width": m.get("width"), "height": m.get("height"), "refresh": round(float(m.get("refreshRate") or 0), 3),
            "x": m.get("x"), "y": m.get("y"), "scale": m.get("scale"), "transform": m.get("transform", 0),
            "disabled": bool(m.get("disabled")), "focused": bool(m.get("focused")),
            "modes": [x for x in (m.get("availableModes") or []) if MODE_RE.match(x)],
        })
    return out


def _closest_scale(v: float) -> Optional[float]:
    for s in SCALES:
        if abs(s - v) < 0.002:
            return s
    return None


def line_for(mon: Dict[str, Any], mode: str, position: str, scale: float) -> str:
    return "desc:%s,%s,%s,%s" % (mon["description"], mode.replace("Hz", ""), position, ("%g" % scale))


def current_line(mon: Dict[str, Any]) -> str:
    if mon["disabled"]:
        return "desc:%s,disable" % mon["description"]
    return "desc:%s,%dx%d@%.3f,%dx%d,%g" % (mon["description"], mon["width"], mon["height"], mon["refresh"], mon["x"], mon["y"], mon["scale"])


def validate_change(mon: Dict[str, Any], mode: str, position: str, scale: float) -> List[str]:
    problems = []
    if not DESC_RE.match(mon["description"] or ""):
        problems.append("monitor %s has no usable description; use monitors.conf instead" % mon["name"])
    if mode != "preferred" and mode not in mon["modes"]:
        problems.append("%s does not offer the mode %s (available: %s)" % (mon["name"], mode, ", ".join(mon["modes"][:6])))
    if not POS_RE.match(position):
        problems.append("position must be 'auto' or XxY")
    if _closest_scale(scale) is None:
        problems.append("scale must be one of %s" % ", ".join("%g" % s for s in SCALES))
    return problems


def _write_fragment(lines: List[str]) -> None:
    path = fragment_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# Generated by `aether display` (Settings → Displays) on %s.\n" % time.strftime("%Y-%m-%d %H:%M"))
        fh.write("# Sourced after ~/.config/hypr/monitors.conf; remove a line to fall back to it.\n")
        for l in lines:
            fh.write("monitor = %s\n" % l)
    os.replace(tmp, path)


def _read_fragment_lines() -> List[str]:
    try:
        with open(fragment_path(), encoding="utf-8") as fh:
            return [l.split("=", 1)[1].strip() for l in fh if l.startswith("monitor =")]
    except OSError:
        return []


def _apply_live(ctx: Context, lines: List[str]) -> bool:
    ok = True
    for l in lines:
        ok = ctx.run(["hyprctl", "keyword", "monitor", l], timeout=10).ok and ok
    return ok


def apply(ctx: Context, name: str, mode: str, position: str = "auto", scale: float = 1.0,
          confirm_within: int = 15, spawn=None) -> Dict[str, Any]:
    mons = monitors(ctx)
    if mons is None:
        return {"ok": False, "problems": ["Hyprland is not running"]}
    mon = next((m for m in mons if m["name"] == name), None)
    if mon is None:
        return {"ok": False, "problems": ["no monitor named %r" % name]}
    scale = _closest_scale(float(scale)) or scale
    problems = validate_change(mon, mode, position, scale)
    if problems:
        return {"ok": False, "problems": problems}
    if os.path.exists(token_path()):
        return {"ok": False, "problems": ["a previous display change is still waiting for confirmation"]}
    previous_fragment = _read_fragment_lines()
    previous_live = [current_line(m) for m in mons]
    new_line = line_for(mon, mode, position, scale)
    lines = [l for l in previous_fragment if not l.startswith("desc:%s," % mon["description"])] + [new_line]
    os.makedirs(state_dir(), exist_ok=True)
    with open(token_path(), "w", encoding="utf-8") as fh:
        json.dump({"previousFragment": previous_fragment, "previousLive": previous_live, "created": time.time(),
                   "timeout": confirm_within}, fh)
    _write_fragment(lines)
    live = _apply_live(ctx, [new_line])
    if confirm_within > 0:
        (spawn or _spawn_watchdog)(confirm_within)
    return {"ok": True, "applied": new_line, "live": live, "confirmWithin": confirm_within}


def _spawn_watchdog(seconds: int) -> None:
    lib = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    subprocess.Popen([sys.executable, "-c", "import sys; sys.path.insert(0, %r); from aether import displays; displays.watchdog(%d)" % (lib, seconds)],
                     stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)


def confirm() -> bool:
    try:
        os.remove(token_path())
        return True
    except FileNotFoundError:
        return False


def revert(ctx: Context) -> Dict[str, Any]:
    try:
        with open(token_path(), encoding="utf-8") as fh:
            pending = json.load(fh)
    except (OSError, ValueError):
        return {"ok": False, "error": "no pending display change"}
    _write_fragment(pending.get("previousFragment", []))
    live = _apply_live(ctx, [l for l in pending.get("previousLive", []) if isinstance(l, str)])
    try:
        os.remove(token_path())
    except OSError:
        pass
    return {"ok": True, "live": live}


def watchdog(seconds: int, ctx: Optional[Context] = None, sleep=time.sleep) -> bool:
    """Runs detached. Returns True if it reverted."""
    from .util import default_context
    sleep(seconds)
    if not os.path.exists(token_path()):
        return False
    revert(ctx or default_context())
    if ctx is None:
        subprocess.run(["notify-send", "-u", "critical", "Display change reverted", "It wasn't confirmed within %d s." % seconds],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
    return True


# -- profiles -------------------------------------------------------------------

def _load_profiles() -> Dict[str, Any]:
    try:
        with open(profiles_path(), encoding="utf-8") as fh:
            data = json.load(fh)
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def save_profile(ctx: Context, name: str) -> Dict[str, Any]:
    if not re.match(r"^[a-z0-9][a-z0-9-]{0,39}$", name):
        return {"ok": False, "error": "profile names are lowercase letters, digits and '-'"}
    mons = monitors(ctx)
    if not mons:
        return {"ok": False, "error": "Hyprland is not running"}
    data = _load_profiles()
    data[name] = {"monitors": sorted(m["description"] for m in mons), "lines": [current_line(m) for m in mons]}
    os.makedirs(os.path.dirname(profiles_path()), exist_ok=True)
    tmp = profiles_path() + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2)
    os.replace(tmp, profiles_path())
    return {"ok": True, "name": name, "monitors": data[name]["monitors"]}


def auto_profile(ctx: Context) -> Dict[str, Any]:
    """Apply the saved profile whose monitor set equals the connected set."""
    mons = monitors(ctx)
    if not mons:
        return {"ok": False, "error": "Hyprland is not running"}
    connected = sorted(m["description"] for m in mons)
    for name, prof in _load_profiles().items():
        if prof.get("monitors") == connected:
            lines = [l for l in prof.get("lines", []) if isinstance(l, str) and l.startswith("desc:") and "\n" not in l]
            _write_fragment(lines)
            return {"ok": True, "applied": name, "live": _apply_live(ctx, lines)}
    return {"ok": True, "applied": None}
