"""Colour palettes: read the shell's palette table and apply it to things
the shell can't theme itself (terminals, Hyprland borders).

The table lives in the shell (theme/Palettes.js) and is parsed here, so
there is exactly one definition of every colour.
"""

from __future__ import annotations

import json
import os
import re
import time
from typing import Any, Dict, List, Optional, Tuple

from .util import Context, config_dir

_BLOCK = re.compile(r"// PALETTES-BEGIN\s*\nvar palettes = (\{.*?\});\s*\n// PALETTES-END", re.S)
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
TOKENS = ("bg0", "bg1", "bg2", "glass", "surface", "surfaceHover", "surfaceActive", "border", "borderStrong",
          "text", "text2", "text3", "accent", "accentAlt", "success", "warning", "danger", "info")

_CACHE: Optional[Dict[str, Dict[str, Any]]] = None


def shell_dir() -> str:
    env = os.environ.get("AETHER_SHELL_DIR")
    if env:
        return env
    here = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    cand = os.path.join(here, "config", "quickshell", "aether-shell")
    if os.path.isdir(cand):
        return cand
    return os.path.join(os.path.dirname(config_dir()), "quickshell", "aether-shell")


def load(include_user: bool = True) -> Dict[str, Dict[str, Any]]:
    """Built-in palettes, plus validated user themes (which can't shadow them)."""
    table = dict(_builtin())
    if include_user:
        from . import themes
        for tid, theme in themes.listing().items():
            table.setdefault(tid, theme)
    return table


def builtin_ids() -> List[str]:
    return list(_builtin())


def _builtin() -> Dict[str, Dict[str, Any]]:
    global _CACHE
    if _CACHE is None:
        path = os.path.join(shell_dir(), "theme", "Palettes.js")
        with open(path, "r", encoding="utf-8") as fh:
            m = _BLOCK.search(fh.read())
        if not m:
            raise ValueError("%s: palette block not found" % path)
        _CACHE = json.loads(m.group(1))
    return _CACHE


def ids() -> List[str]:
    try:
        return [k for k in load() if k != "aether-light"]
    except (OSError, ValueError):
        return ["aether"]


def resolve(palette_id: str, dark: bool = True) -> Dict[str, Any]:
    table = load()
    if palette_id not in table or palette_id in ("aether", "aether-light"):
        return table["aether" if dark else "aether-light"]
    return table[palette_id]


def _rgba(hex_colour: str, alpha: str) -> str:
    return "rgba(%s%s)" % (hex_colour.lstrip("#").lower(), alpha)


def render_kitty(p: Dict[str, Any], accent: str) -> str:
    lines = [
        "# Generated by `aether theme apply` — %s. Do not edit; change the palette in" % p["label"],
        "# Settings → Appearance (or `aether theme palette <id>`) instead.",
        "background            %s" % p["bg0"],
        "foreground            %s" % p["text"],
        "cursor                %s" % accent,
        "cursor_text_color     %s" % p["bg0"],
        "selection_background  %s" % p["surfaceActive"],
        "selection_foreground  %s" % p["text"],
        "url_color             %s" % p["info"],
        "active_border_color   %s" % accent,
        "inactive_border_color %s" % p["border"],
        "active_tab_background   %s" % accent,
        "active_tab_foreground   %s" % p["bg0"],
        "inactive_tab_background %s" % p["bg2"],
        "inactive_tab_foreground %s" % p["text2"],
        "tab_bar_background      %s" % p["bg0"],
    ]
    lines += ["color%-2d %s" % (i, c) for i, c in enumerate(p["ansi"])]
    return "\n".join(lines) + "\n"


def render_foot(p: Dict[str, Any], accent: str) -> str:
    strip = lambda c: c.lstrip("#").lower()  # noqa: E731
    lines = ["# Generated by `aether theme apply` — %s." % p["label"], "[colors]",
             "background=%s" % strip(p["bg0"]), "foreground=%s" % strip(p["text"]),
             "selection-background=%s" % strip(p["surfaceActive"]), "selection-foreground=%s" % strip(p["text"])]
    lines += ["regular%d=%s" % (i, strip(c)) for i, c in enumerate(p["ansi"][:8])]
    lines += ["bright%d=%s" % (i, strip(c)) for i, c in enumerate(p["ansi"][8:])]
    return "\n".join(lines) + "\n"


def render_alacritty(p: Dict[str, Any], accent: str) -> str:
    names = ("black", "red", "green", "yellow", "blue", "magenta", "cyan", "white")
    out = ["# Generated by `aether theme apply` — %s." % p["label"], "[colors.primary]",
           'background = "%s"' % p["bg0"], 'foreground = "%s"' % p["text"], "", "[colors.cursor]",
           'cursor = "%s"' % accent, 'text = "%s"' % p["bg0"], "", "[colors.normal]"]
    out += ['%s = "%s"' % (n, c) for n, c in zip(names, p["ansi"][:8])]
    out += ["", "[colors.bright]"] + ['%s = "%s"' % (n, c) for n, c in zip(names, p["ansi"][8:])]
    return "\n".join(out) + "\n"


def render_ghostty(p: Dict[str, Any], accent: str) -> str:
    out = ["# Generated by `aether theme apply` — %s." % p["label"],
           "background = %s" % p["bg0"], "foreground = %s" % p["text"], "cursor-color = %s" % accent,
           "selection-background = %s" % p["surfaceActive"], "selection-foreground = %s" % p["text"]]
    out += ["palette = %d=%s" % (i, c) for i, c in enumerate(p["ansi"])]
    return "\n".join(out) + "\n"


def render_hypr(p: Dict[str, Any], accent: str) -> str:
    return (
        "# Generated by `aether theme apply` on %s — %s.\n"
        "# Window border colours follow the shell palette. Sourced by hyprland.conf.\n"
        "general {\n"
        "    col.active_border = %s %s 45deg\n"
        "    col.inactive_border = %s\n"
        "}\n"
    ) % (time.strftime("%Y-%m-%d %H:%M"), p["label"], _rgba(accent, "ee"), _rgba(p["accentAlt"], "ee"), _rgba(p["border"], "99"))


TERMINALS = {
    "kitty": ("kitty-theme.conf", render_kitty, "include ~/.config/aether-shell/terminal/kitty-theme.conf   (already in AetherOS's kitty.conf)"),
    "foot": ("foot-theme.ini", render_foot, "include=~/.config/aether-shell/terminal/foot-theme.ini   in ~/.config/foot/foot.ini"),
    "alacritty": ("alacritty-theme.toml", render_alacritty, 'import = ["~/.config/aether-shell/terminal/alacritty-theme.toml"]   under [general] in alacritty.toml'),
    "ghostty": ("ghostty-theme", render_ghostty, "config-file = ~/.config/aether-shell/terminal/ghostty-theme   in ~/.config/ghostty/config"),
}


def _write(path: str, text: str) -> bool:
    try:
        with open(path, "r", encoding="utf-8") as fh:
            if fh.read() == text:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, path)
    return True


def apply(ctx: Context, palette_id: str, accent: Optional[str], dark: bool, reload_apps: bool = True) -> Dict[str, Any]:
    """Write terminal + Hyprland theme fragments for ``palette_id``.

    Only AetherOS's own generated files are written; no terminal's main
    config is touched. Returns what changed and how to wire up terminals
    that AetherOS doesn't configure itself."""
    p = resolve(palette_id, dark)
    # The accent override only applies to the built-in palette; a named
    # scheme keeps its own accent so it stays recognisable.
    builtin = palette_id in ("aether", "aether-light") or palette_id not in load()
    acc = accent if (builtin and accent and HEX.match(accent)) else p["accent"]
    base = config_dir()
    written: List[str] = []
    for name, (fname, render, _hint) in TERMINALS.items():
        path = os.path.join(base, "terminal", fname)
        if _write(path, render(p, acc)):
            written.append(path)
    t = _terminal_settings()
    for fname, text in (("kitty-local.conf", render_kitty_local(t)),
                        ("zsh-profile.zsh", render_zsh_profile(t, os.path.join(os.path.dirname(os.path.dirname(shell_dir())), "zsh")))):
        path = os.path.join(base, "terminal", fname)
        if _write(path, text):
            written.append(path)
    hypr_path = os.path.join(base, "hypr", "theme.conf")
    if _write(hypr_path, render_hypr(p, acc)):
        written.append(hypr_path)
    reloaded: List[str] = []
    if reload_apps and written and ctx.is_live:
        # kitty re-reads its config (including our include) on SIGUSR1.
        if ctx.which("pkill") and ctx.run(["pkill", "-USR1", "-x", "kitty"], timeout=5).ok:
            reloaded.append("kitty")
    return {"palette": palette_id, "label": p["label"], "accent": acc, "written": written, "reloaded": reloaded,
            "hints": {n: h for n, (_f, _r, h) in TERMINALS.items()}}


def _terminal_settings() -> Dict[str, Any]:
    from . import config as config_mod
    out = dict(config_mod.defaults()["terminal"])
    data, _err = config_mod.load()
    clean, _p = config_mod.validate({"terminal": (data or {}).get("terminal", {})})
    out.update(clean.get("terminal", {}))
    return out


def render_kitty_local(t: Dict[str, Any]) -> str:
    return "\n".join([
        "# Generated by `aether theme apply` from Settings → Terminal. Do not edit.",
        "font_family          %s" % t["fontFamily"],
        "font_size            %.1f" % float(t["fontSize"]),
        "background_opacity   %.2f" % float(t["opacity"]),
        "window_padding_width %d" % int(t["padding"]),
        "cursor_shape         %s" % t["cursorShape"],
    ]) + "\n"


ZSH_PROFILES = ("minimal", "developer", "power", "custom")


def render_zsh_profile(t: Dict[str, Any], repo_zsh_dir: str) -> str:
    name = t["zshProfile"] if t["zshProfile"] in ZSH_PROFILES else "developer"
    head = "# Generated by `aether theme apply` (Settings → Terminal → Zsh profile: %s).\n" % name
    if name == "custom":
        path = t.get("customProfile") or ""
        if not path:
            return head + "# No custom file chosen: nothing extra is loaded.\n"
        # Quoted with zsh's (q) rules: the path is data, never code.
        quoted = "'" + path.replace("'", "'\\''") + "'"
        return head + "[ -f %s ] && source %s\n" % (quoted, quoted)
    return head + "source '%s/profiles/%s.zsh'\n" % (repo_zsh_dir.replace("'", ""), name)


def detect_terminals(ctx: Context) -> List[Dict[str, Any]]:
    known = ("kitty", "ghostty", "wezterm", "alacritty", "foot", "gnome-terminal", "ptyxis", "konsole")
    return [{"name": n, "installed": ctx.which(n) is not None, "themed": n in TERMINALS} for n in known]
