"""Workspaces: per-app workspace rules (version-aware Hyprland syntax) and
session save/restore.

Session restore launches apps from their *desktop entries* (resolved from the
saved window class), never from stored command lines: a tampered
session.json can name an installed app and a workspace, nothing else.
"""

from __future__ import annotations

import json
import os
import re
import shlex
import time
from typing import Any, Dict, List, Optional

from . import apps
from .hw import system
from .util import Context, config_dir, parse_version, version_at_least

CLASS_RE = re.compile(r"^[\w.+-]{1,128}$")


def rules_path() -> str:
    return os.path.join(config_dir(), "hypr", "apprules.conf")


def session_path() -> str:
    return os.path.join(config_dir(), "session.json")


def render_rules(rules: List[Dict[str, Any]], v2: bool) -> str:
    out = ["# Generated by `aether workspace rules` from Settings → Workspaces (%s syntax)."
           % ("Hyprland ≥ 0.53" if v2 else "Hyprland < 0.53")]
    for r in rules:
        app = str(r.get("app", ""))
        ws = r.get("workspace")
        if not CLASS_RE.match(app) or not isinstance(ws, int) or not 1 <= ws <= 99:
            continue
        target = "%d%s" % (ws, " silent" if r.get("silent") else "")
        pattern = "^(%s)$" % re.escape(app)
        out.append(("windowrule = match:class %s, workspace %s" % (pattern, target)) if v2
                   else ("windowrule = workspace %s, class:%s" % (target, pattern)))
    return "\n".join(out) + "\n"


def write_rules(ctx: Context, rules: List[Dict[str, Any]]) -> Dict[str, Any]:
    ver = parse_version(system.hyprland_version(ctx))
    v2 = bool(ver and version_at_least(ver, (0, 53)))
    os.makedirs(os.path.dirname(rules_path()), exist_ok=True)
    tmp = rules_path() + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_rules(rules, v2))
    os.replace(tmp, rules_path())
    reloaded = bool(ctx.env.get("HYPRLAND_INSTANCE_SIGNATURE")) and ctx.run(["hyprctl", "reload", "config-only"], timeout=10).ok
    return {"ok": True, "path": rules_path(), "syntax": "v2" if v2 else "legacy", "reloaded": reloaded}


def save_session(ctx: Context) -> Dict[str, Any]:
    res = ctx.run(["hyprctl", "-j", "clients"], timeout=5)
    if not res.ok:
        return {"ok": False, "error": "Hyprland is not running"}
    try:
        clients = json.loads(res.out)
    except ValueError:
        return {"ok": False, "error": "unexpected hyprctl output"}
    catalog = apps.all_apps()
    entries, skipped = [], []
    for c in clients:
        ws = (c.get("workspace") or {}).get("id", -1)
        cls = c.get("class") or c.get("initialClass") or ""
        if not isinstance(ws, int) or ws < 1 or not CLASS_RE.match(cls):
            continue
        app = apps.for_class(cls, catalog)
        if app is None:
            skipped.append(cls)
            continue
        entries.append({"app": app["id"], "class": cls, "workspace": ws})
    # One entry per (app, workspace): multiple windows of an app reopen once.
    uniq = {(e["app"], e["workspace"]): e for e in entries}
    data = {"saved": time.strftime("%Y-%m-%dT%H:%M:%S"), "entries": list(uniq.values())}
    os.makedirs(os.path.dirname(session_path()), exist_ok=True)
    tmp = session_path() + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2)
    os.replace(tmp, session_path())
    return {"ok": True, "saved": len(data["entries"]), "skipped": sorted(set(skipped))}


def restore_session(ctx: Context, dry_run: bool = False) -> Dict[str, Any]:
    try:
        with open(session_path(), encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {"ok": False, "error": "no saved session"}
    running = set()
    res = ctx.run(["hyprctl", "-j", "clients"], timeout=5)
    if res.ok:
        try:
            running = {(c.get("class") or "").lower() for c in json.loads(res.out)}
        except ValueError:
            pass
    catalog = apps.all_apps()
    launched, skipped = [], []
    for e in data.get("entries", [])[:40] if isinstance(data.get("entries"), list) else []:
        if not isinstance(e, dict):
            continue
        app = catalog.get(str(e.get("app", "")))
        ws = e.get("workspace")
        if app is None or not isinstance(ws, int) or not 1 <= ws <= 99:
            skipped.append(str(e.get("app")))
            continue
        if str(e.get("class", "")).lower() in running:
            skipped.append("%s (already open)" % app["id"])
            continue
        try:
            argv = apps.argv(app)
        except ValueError as exc:
            skipped.append(str(exc))
            continue
        # hyprctl exec runs its argument through a shell: every word is quoted.
        cmd = "[workspace %d silent] %s" % (ws, " ".join(shlex.quote(a) for a in argv))
        if not dry_run:
            ctx.run(["hyprctl", "dispatch", "exec", cmd], timeout=5)
        launched.append({"app": app["id"], "workspace": ws, "command": cmd})
    return {"ok": True, "launched": launched, "skipped": skipped, "dryRun": dry_run}
