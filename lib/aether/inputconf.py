"""Keyboard, mouse and touchpad settings → Hyprland.

Layouts, variants and options are validated against the system's own XKB
rules list (/usr/share/X11/xkb/rules/evdev.lst), so a typo can't produce an
`input` block that leaves you without a keyboard layout. Applied two ways:
live (`hyprctl --batch keyword …`) and persisted (input.conf, sourced by
hyprland.conf after its own input block).
"""

from __future__ import annotations

import os
import re
import time
from typing import Any, Dict, List, Optional, Tuple

from .util import Context, config_dir

EVDEV_LST = ("/usr/share/X11/xkb/rules/evdev.lst", "/usr/share/X11/xkb/rules/base.lst")
SAFE = re.compile(r"^[A-Za-z0-9_:+()-]*$")


def xkb_catalog(ctx: Context) -> Dict[str, Any]:
    """{layouts: {code: desc}, variants: {layout: {variant: desc}}, options: {opt: desc}}."""
    text = None
    for p in EVDEV_LST:
        text = ctx.read(p)
        if text:
            break
    out: Dict[str, Any] = {"layouts": {}, "variants": {}, "options": {}, "available": bool(text)}
    section = None
    for line in (text or "").splitlines():
        if line.startswith("! "):
            section = line[2:].strip()
            continue
        m = re.match(r"^\s+(\S+)\s+(.*)$", line)
        if not m:
            continue
        key, desc = m.group(1), m.group(2).strip()
        if section == "layout":
            out["layouts"][key] = desc
        elif section == "variant":
            layout = desc.split(":", 1)[0]
            out["variants"].setdefault(layout, {})[key] = desc.split(":", 1)[-1].strip()
        elif section == "option" and ":" in key:
            out["options"][key] = desc
    return out


def validate(settings: Dict[str, Any], catalog: Dict[str, Any]) -> List[str]:
    problems = []
    layouts = [x.strip() for x in str(settings.get("kbLayout", "")).split(",")]
    variants = [x.strip() for x in str(settings.get("kbVariant", "")).split(",")] if settings.get("kbVariant") else []
    options = [x.strip() for x in str(settings.get("kbOptions", "")).split(",") if x.strip()]
    for s in [settings.get("kbLayout", ""), settings.get("kbVariant", ""), settings.get("kbOptions", "")]:
        if not SAFE.match(str(s).replace(",", "")):
            problems.append("keyboard settings may only contain letters, digits and _ : + ( ) -")
            return problems
    if not catalog["available"]:
        return problems  # can't check without the rules file; the safe-charset check still applies
    for lay in layouts:
        if lay not in catalog["layouts"]:
            problems.append("unknown keyboard layout %r" % lay)
    if len(variants) > len(layouts):
        problems.append("more variants than layouts")
    for lay, var in zip(layouts, variants):
        if var and var not in catalog["variants"].get(lay, {}):
            problems.append("layout %r has no variant %r" % (lay, var))
    for opt in options:
        if opt not in catalog["options"]:
            problems.append("unknown XKB option %r" % opt)
    return problems


def _b(v: Any) -> str:
    return "true" if v else "false"


def render(s: Dict[str, Any]) -> str:
    return "\n".join([
        "# Generated by `aether input apply` on %s from Settings → Keyboard / Mouse." % time.strftime("%Y-%m-%d %H:%M"),
        "input {",
        "    kb_layout = %s" % s["kbLayout"],
        "    kb_variant = %s" % s["kbVariant"],
        "    kb_options = %s" % s["kbOptions"],
        "    repeat_rate = %d" % int(s["repeatRate"]),
        "    repeat_delay = %d" % int(s["repeatDelay"]),
        "    sensitivity = %.2f" % float(s["sensitivity"]),
        "    accel_profile = %s" % s["accelProfile"],
        "    natural_scroll = %s" % _b(s["naturalScroll"]),
        "    scroll_factor = %.2f" % float(s["scrollFactor"]),
        "    touchpad {",
        "        natural_scroll = %s" % _b(s["touchpadNaturalScroll"]),
        "        tap-to-click = %s" % _b(s["tapToClick"]),
        "        disable_while_typing = %s" % _b(s["disableWhileTyping"]),
        "    }",
        "}",
    ]) + "\n"


def live_commands(s: Dict[str, Any]) -> List[str]:
    return [
        "keyword input:kb_layout %s" % s["kbLayout"],
        "keyword input:kb_variant %s" % (s["kbVariant"] or ""),
        "keyword input:kb_options %s" % (s["kbOptions"] or ""),
        "keyword input:repeat_rate %d" % int(s["repeatRate"]),
        "keyword input:repeat_delay %d" % int(s["repeatDelay"]),
        "keyword input:sensitivity %.2f" % float(s["sensitivity"]),
        "keyword input:accel_profile %s" % s["accelProfile"],
        "keyword input:natural_scroll %s" % _b(s["naturalScroll"]),
        "keyword input:scroll_factor %.2f" % float(s["scrollFactor"]),
        "keyword input:touchpad:natural_scroll %s" % _b(s["touchpadNaturalScroll"]),
        "keyword input:touchpad:tap-to-click %s" % _b(s["tapToClick"]),
        "keyword input:touchpad:disable_while_typing %s" % _b(s["disableWhileTyping"]),
    ]


def path() -> str:
    return os.path.join(config_dir(), "hypr", "input.conf")


def apply(ctx: Context, s: Dict[str, Any], live: bool = True) -> Dict[str, Any]:
    if s.get("accelProfile") not in ("adaptive", "flat"):
        return {"ok": False, "problems": ["accelProfile must be adaptive or flat"]}
    problems = validate(s, xkb_catalog(ctx))
    if problems:
        return {"ok": False, "problems": problems}
    os.makedirs(os.path.dirname(path()), exist_ok=True)
    tmp = path() + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(s))
    os.replace(tmp, path())
    applied = False
    if live and ctx.env.get("HYPRLAND_INSTANCE_SIGNATURE") and ctx.which("hyprctl"):
        applied = ctx.run(["hyprctl", "--batch", " ; ".join(live_commands(s))], timeout=10).ok
    return {"ok": True, "path": path(), "live": applied}
