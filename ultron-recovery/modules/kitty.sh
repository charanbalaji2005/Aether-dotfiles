# shellcheck shell=bash
# ULTRON RECOVERY — Kitty: kitty.conf, its includes, the configured font.

KITTY_DIR="$HOME/.config/kitty"

mod_kitty_paths() { echo "$KITTY_DIR"; }
mod_kitty_deps()  { printf '%s\n' "kitty:kitty" "fc-list:fontconfig"; }

kitty_missing_includes() {
    local inc
    [ -f "$KITTY_DIR/kitty.conf" ] || return 0
    while IFS= read -r inc; do
        inc="${inc/#\~/$HOME}"
        case "$inc" in *'*'*|'') continue ;; /*) ;; *) inc="$KITTY_DIR/$inc" ;; esac
        [ -e "$inc" ] || echo "$inc"
    done < <(sed -nE 's/^[[:space:]]*(include|globinclude)[[:space:]]+(.+)$/\2/p' "$KITTY_DIR/kitty.conf" | sed 's/[[:space:]]*$//')
}

kitty_font() {  # the effective font_family (last one wins, includes after)
    local f files=("$KITTY_DIR/kitty.conf") inc
    while IFS= read -r inc; do files+=("$inc"); done < <(sed -nE 's/^[[:space:]]*include[[:space:]]+(.+)$/\1/p' "$KITTY_DIR/kitty.conf" 2>/dev/null | sed "s|^~|$HOME|")
    for f in "${files[@]}"; do [ -f "$f" ] && sed -nE 's/^[[:space:]]*font_family[[:space:]]+(.+)$/\1/p' "$f"; done | tail -1 | sed 's/[[:space:]]*$//'
}

mod_kitty_check() {
    local p0=${#UR_PROBLEMS[@]} m font
    if [ -L "$KITTY_DIR" ] && [ ! -e "$KITTY_DIR" ]; then problem kitty "~/.config/kitty is a broken link → $(readlink "$KITTY_DIR")"; return; fi
    [ -f "$KITTY_DIR/kitty.conf" ] || { problem kitty "~/.config/kitty/kitty.conf is missing"; return; }
    command -v kitty >/dev/null 2>&1 || problem kitty "Kitty is not installed (sudo dnf install kitty)"
    while IFS= read -r m; do [ -n "$m" ] && problem kitty "included file missing: ${m/#$HOME/\~}"; done < <(kitty_missing_includes)
    font="$(kitty_font)"
    if [ -n "$font" ] && [ "$font" != monospace ] && ! font_family_installed "$font"; then
        problem kitty "font '$font' is not installed"
    fi
    [ "${#UR_PROBLEMS[@]}" -eq "$p0" ] && check_ok "Kitty: config, includes and font '${font:-default}' OK"
    return 0
}

mod_kitty_repair() {
    repair_link "$KITTY_DIR" config/kitty
    repair_deleted_tracked config/kitty
    local m
    while IFS= read -r m; do
        [ -n "$m" ] || continue
        case "$m" in "$HOME"/*) change "create empty placeholder for missing include ${m/#$HOME/\~} (regenerated by: aether theme apply)" sh -c 'mkdir -p "$(dirname "$1")" && : > "$1"' sh "$m" ;; esac
    done < <(kitty_missing_includes)
    repair_full_restore kitty config/kitty
    local font; font="$(kitty_font)"
    if [ -n "$font" ] && ! font_family_installed "$font"; then
        ui_info "Missing font: use 'Repair Fonts and Wallpapers' (it installs JetBrainsMono Nerd Font)."
    fi
}
